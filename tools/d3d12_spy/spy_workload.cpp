static int g_fail;
static void check(HRESULT hr, const char* what) {
    printf("%-46s 0x%08lx %s\n", what, (unsigned long)hr, SUCCEEDED(hr) ? "OK" : "FAIL");
    fflush(stdout);
    if (FAILED(hr)) ++g_fail;
}
#define CHECK(expr) check((expr), #expr)
#define MUST(expr)                    \
    do {                              \
        HRESULT _hr = (expr);         \
        check(_hr, #expr);            \
        if (FAILED(_hr)) return _hr;  \
    } while (0)

struct Args {
    const char* mode = "device";
    bool warp = false;
    int adapter = -1;
    int frames = 5;
    bool debug = false;  // enable the D3D12 debug layer -- the retail runtime and the
                         // debug layer enforce DIFFERENT caps rules, and telling them
                         // apart is the whole point of the `range` arm.
    int hold = 0;  // seconds to stay alive after setup, so the caller can read the
                   // process's loaded-module list. "Which d3d10warp.dll is mapped" is the
                   // check DDI_REFERENCE.md §15.2 demands before trusting a null result.
};

