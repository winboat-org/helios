// spy_workload.cpp — the four D12-G5 workloads that drive the WARP spy proxy.
//
//   device    DDI_REFERENCE.md §15.2 workload (a): D3D12CreateDevice and nothing else.
//             Settles #1 (which caps the runtime demands, in order), #5 and #6 (the
//             Interface/Version split and which token this Windows negotiates), #8
//             (whether pfnGetSupportedVersions is really a two-call query), #18.
//   queue     workload (b): + command queue, pool/recorder/list, Close. Settles #3 and #9.
//   window    workload (c): + swapchain, clear, present. Settles #2, #4, #7, #16. NO
//             SHADERS AT ALL, which is the point: it separates "the runtime always asks
//             for X" from "the app happened to need X".
//   triangle  workload (d): + a draw with TWO pipelines — one whose shaders are SM 5.1
//             DXBC compiled at runtime by D3DCompile, one whose shaders are SM 6.0 DXIL
//             compiled at build time by dxc. Settles #14 / Q1 for both encodings in one
//             process, which a single-shader-model run cannot do.
//
// ⚠ Why these and not `dx-samples-research-only/.../D3D12HelloWorld`, which GATES.md §4.6
// names: that sample carries the Agility SDK exports
// (`D3D12HelloWindow.cpp:15-16`: `D3D12SDKVersion = 618`, `D3D12SDKPath = ".\\D3D12\\"`),
// so whether the experiment runs against THIS Windows build's D3D12Core.dll or against a
// NuGet one depends on whether a `D3D12\` directory happens to sit beside the exe. This
// gate is a measurement OF the shipping runtime; a silent runtime substitution would
// invalidate every line of the log. These probes carry no such export and need no NuGet
// package (the samples need `include/d3dx12/d3dx12.h` from Microsoft.Direct3D.D3D12
// 1.618.3, which is not vendored in this tree).
//
// ⛔ `window` and `triangle` create a window, so they must run in SESSION 1 via a cloned
// scheduled task — a windowed run launched from win_exec lands in session 0, which has no
// desktop, and fakes a driver regression (memory lease-gate-falsified-60th).
//
// build: build.ps1

